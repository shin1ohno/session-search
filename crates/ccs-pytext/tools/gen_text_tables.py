#!/usr/bin/env python3
"""Generate text properties from the same Python/Unicode version as the corpus."""
import pathlib
import re
import sys
import subprocess
import unicodedata

if sys.version_info[:3] != (3, 13, 5) or unicodedata.unidata_version != '15.1.0':
    raise SystemExit('requires Python 3.13.5 / Unicode 15.1.0')
out = ['// Generated by tools/gen_text_tables.py; Python 3.13.5 / Unicode 15.1.0.']
for name, predicate in [('SPACE', str.isspace), ('WORD', lambda c: re.fullmatch(r'\w', c) is not None)]:
    ranges = []
    for cp in range(0x110000):
        if predicate(chr(cp)):
            if ranges and ranges[-1][1] == cp - 1:
                ranges[-1][1] = cp
            else:
                ranges.append([cp, cp])
    out.append(f'pub const {name}: &[(u32, u32)] = &[')
    out.extend(f'    (0x{a:x}, 0x{b:x}),' for a, b in ranges)
    out.append('];')
for name, operation in [('CASEFOLD', str.casefold), ('LOWER', str.lower)]:
    out.append(f'pub const {name}: &[(u32, &str)] = &[')
    for cp in range(0x110000):
        value = operation(chr(cp))
        if value != chr(cp):
            escaped = ''.join('\\u{%x}' % ord(c) for c in value)
            out.append(f'    (0x{cp:x}, "{escaped}"),')
    out.append('];')
# Python urlsplit rejects authority characters whose NFKC introduces separators.
invalid = [cp for cp in range(128, 0x110000)
           if any(c in '/?#@:' for c in unicodedata.normalize('NFKC', chr(cp)))]
out.append('pub const INVALID_NETLOC: &[u32] = &[')
out.extend(f'    0x{cp:x},' for cp in invalid)
out.append('];')
pathlib.Path(__file__).resolve().parents[1].joinpath('src/tables.rs').write_text('\n'.join(out) + '\n')

subprocess.run(["rustfmt", str(pathlib.Path(__file__).resolve().parents[1] / "src/tables.rs")], check=True)
