"""Verify the diagnostic repr table against the pinned Python Unicode oracle."""
from pathlib import Path
import re
import sys
import unicodedata

START = '// BEGIN PYTHON NONPRINTABLE'
END = '// END PYTHON NONPRINTABLE'

def generated():
    if unicodedata.unidata_version != '15.1.0':
        raise RuntimeError('repr table requires Python 3.13 / Unicode 15.1.0')
    ranges = []
    for point in range(0x110000):
        if not chr(point).isprintable():
            if ranges and ranges[-1][1] == point - 1: ranges[-1][1] = point
            else: ranges.append([point, point])
    return START + '\n// Generated by tests/resume_printable.py; Python 3.13.5 / Unicode 15.1.0.\nconst NONPRINTABLE: &[(u32, u32)] = &[\n' + ''.join('    (0x%x, 0x%x),\n' % tuple(pair) for pair in ranges) + '];\n' + END

def verify(write=False):
    source = Path(__file__).resolve().parents[1] / 'src/resume.rs'
    code = source.read_text(); block = generated()
    if write:
        if START in code: code = re.sub(START + '.*?' + END, block, code, flags=re.S)
        else: code += '\n' + block + '\n'
        source.write_text(code)
    else:
        actual = code[code.index(START):code.index(END)+len(END)]
        assert actual == block, 'repr table differs from pinned Python'

if __name__ == '__main__': verify('--write' in sys.argv)
